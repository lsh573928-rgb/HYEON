/* 위쪽 큰 글자. 비워 두면 엔진이 정한다.
     hook  — 처음부터 떠 있는 낚는 말 두 줄. 둘째 줄을 비워 두면 "N번째 줄에서 에러 납니다"(N = 대본에서 처음 오류가 나는 줄)
     final — 새해로 넘어가는 순간 바뀌는 맺는 말 두 줄
   예) window.COPY = { final: ['헛삽질은 없었어요', '올해도 수고했어요'] }; */
window.COPY = {
  hook: ['올해 삽질만 했다면', null],
  final: ['헛삽질은 없었습니다', '올해도 수고 많으셨습니다'],
};
